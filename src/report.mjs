// @ts-check
// Reports: Markdown (for people) and JSON (for CI and other tools).

import { formatStatus } from './usage.mjs';
import { RISKY } from './classify.mjs';
import { hourLabel } from './changes.mjs';

/** @param {ReturnType<typeof import('./classify.mjs').classify>} r @param {{ spikes?: any[], toolVersion?: string, duplicates?: any, probe?: any, changes?: any, errors?: any }} [extra] */
export function toJson(r, extra = {}) {
  const fix = (/** @type {any} */ x) => ({ ...x, status: Object.fromEntries(x.status) });
  const brief = (/** @type {any} */ e) => ({ method: e.method, path: e.path, calls: e.calls, errors5xx: e.errors5xx });
  return JSON.stringify(
    {
      schemaVersion: 1,
      ...r,
      endpoints: r.endpoints.map(fix),
      shadow: r.shadow.map(fix),
      noise: r.noise.map(fix),
      serverErrors: r.serverErrors.map(brief),
      errorsBelow: r.errorsBelow.map(brief),
      clientErrors: r.clientErrors.map(fix),
      spikes: extra.spikes || [],
      ...(extra.duplicates ? { duplicates: extra.duplicates } : {}),
      ...(extra.changes ? { changes: extra.changes } : {}),
      ...(extra.errors ? { errors: extra.errors } : {}),
      ...(extra.probe ? { probe: extra.probe } : {}),
      ...(extra.toolVersion ? { tool: { name: 'api-dead-ends', version: extra.toolVersion } } : {}),
    },
    null,
    2,
  ) + '\n';
}

/**
 * @param {ReturnType<typeof import('./classify.mjs').classify>} r
 * @param {{ top?: number, spikes?: any[], duplicates?: any, probe?: any, changes?: any, tz?: string, errors?: any }} [opt]
 */
export function toMarkdown(r, opt = {}) {
  const TOP = opt.top ?? 60;
  const n = (/** @type {number} */ x) => x.toLocaleString('en-US');
  const code = (/** @type {string} */ s) => `\`${String(s).replace(/[\u0000-\u001f\u007f\u2028\u2029]/g, ' ').replace(/`/g, "'").replace(/\|/g, '\\|')}\``;
  const txt = (/** @type {string} */ s) => String(s).replace(/[\u0000-\u001f\u007f\u2028\u2029]/g, ' ').replace(/[|`*_<>#\[\]]/g, (c) => `\\${c}`).slice(0, 240);
  const st = (/** @type {Map<string, number>} */ m, k = 4) => formatStatus(m).split('|').slice(0, k).join(' ');
  const day = (/** @type {string} */ s) => (s ? s.slice(0, 10) : '');
  const pct = (/** @type {number} */ a, /** @type {number} */ b) => `${((a / b) * 100).toFixed(2)}%`;
  const pl = (/** @type {number} */ k, /** @type {string} */ w) => `${n(k)} ${w}${k === 1 ? '' : 's'}`;
  const t = r.totals;
  const th = r.thresholds;
  const L = [];
  const generated = /generated by api-dead-ends/i.test(r.api.title);
  const title = generated ? 'route list' : `${txt(r.api.title)}${r.api.version ? ` · API version ${txt(r.api.version)}` : ''}`;

  L.push(`# api-dead-ends report: ${title}`, '');
  if (!t.requests) {
    L.push('> **No traffic in the usage table.** Every endpoint would look "not seen", which says nothing. Check the source query, the service name and the time window.', '');
    return L.join('\n');
  }
  const E = r.endpoints;
  const winTxt = r.window.days ? pl(r.window.days, 'day') : 'an unknown window (the source gave no dates — pass --days N)';
  L.push('## Summary', '');
  const below5 = r.errorsBelow.reduce((a, e) => a + e.errors5xx, 0);
  L.push(`- **${pl(t.serverErrors, 'endpoint')} with server errors** (5xx ≥ ${+(th.errorShare * 100).toFixed(3)}% of calls and ≥ ${th.errorMin} responses)${t.serverErrorsBelowThreshold ? ` — **and ${n(below5)} more 5xx on ${pl(t.serverErrorsBelowThreshold, 'endpoint')} below that threshold**` : ''}.`);
  if ((opt.spikes || []).length) L.push(`- **${pl(opt.spikes.length, 'recent spike')}**: 5xx over the threshold in the last days and ≥ 3× the days before.`);
  if (t.clientErrors) L.push(`- **${pl(t.clientErrors, 'endpoint')} with many client errors** (4xx other than 401/404 ≥ 10%).`);
  L.push(`- **${pl(t.shadow, 'undocumented endpoint')}** called (not in the spec)${r.shadow.some((x) => RISKY.test(x.path)) ? ' — **includes debug/admin paths**' : ''}${t.ambiguous ? `; plus ${t.ambiguous} path${t.ambiguous === 1 ? '' : 's'} that may be separate routes (see the hint below)` : ''}.`);
  L.push(`- **${pl(t.not_seen, 'endpoint')} not called** in ${winTxt}${t.rare ? `, ${t.rare} rare` : ''}${t.deprecated_in_use ? `, ${t.deprecated_in_use} deprecated but still called` : ''}. Confidence: **${r.window.confidence}**.`);
  L.push(`- ${n(t.requests)} requests in ${pl(t.rows, 'method+path pair')}${r.window.from ? `, ${day(r.window.from)} – ${day(r.window.to)}` : ''}. Operations documented in the spec: ${t.operations} (undocumented ones are counted separately above).`, '');
  L.push('> "Not called" means not seen in this window — not "dead". Monthly jobs, partners and old clients may call less often, and endpoints that do not log are invisible. Treat it as a recommendation to check, never as a reason to delete.', '');

  const sec = (/** @type {string} */ ttl, /** @type {string[]} */ head, /** @type {string[][]} */ rows, /** @type {string} */ note = '') => {
    L.push(`## ${ttl}`, '');
    if (note) L.push(note, '');
    if (!rows.length) { L.push('_None._', ''); return; }
    // drop columns that are empty in every row
    const keepCol = head.map((_, i) => rows.some((row) => row[i] !== '' && row[i] !== undefined));
    const H = head.filter((_, i) => keepCol[i]);
    L.push(`| ${H.join(' | ')} |`, `|${H.map((h) => (/^(Calls|5xx|4xx|Requests|Share)/.test(h) ? '---:' : '---')).join('|')}|`);
    for (const row of rows) L.push(`| ${row.filter((_, i) => keepCol[i]).join(' | ')} |`);
    L.push('');
  };

  const ch = opt.changes;
  if (ch) {
    const ratio = (/** @type {number} */ a, /** @type {number} */ b) => (b ? `${a >= b ? '+' : ''}${(((a / b) - 1) * 100).toFixed(0)}%` : 'new');
    const f1 = (/** @type {number} */ x) => n(Math.round(x));
    sec(`What changed today (${ch.today}, 00:00–${String(ch.upToHour).padStart(2, '0')}:59 UTC vs the same hours before)`, ['', 'Today', 'Before (avg)', 'Change'],
      [['Requests', f1(ch.totals.calls), f1(ch.totals.callsBefore), ratio(ch.totals.calls, ch.totals.callsBefore)], ['5xx', f1(ch.totals.e5), f1(ch.totals.e5Before), ratio(ch.totals.e5, ch.totals.e5Before)]],
      ch.note);
    if (ch.errorsUp.length) sec('5xx up today', ['Method', 'Path', '5xx today', 'Before (avg)', 'Started', 'Calls change'],
      ch.errorsUp.slice(0, TOP).map((/** @type {any} */ x) => [txt(x.method), code(x.path), f1(x.e5), f1(x.e5Before), x.firstErrorHour == null ? '—' : hourLabel(ch.today, x.firstErrorHour, opt.tz), ratio(x.calls, x.callsBefore)]));
    if (ch.clientErrorsUp.length) sec('4xx up today', ['Method', 'Path', '4xx today', 'Before (avg)'],
      ch.clientErrorsUp.slice(0, TOP).map((/** @type {any} */ x) => [txt(x.method), code(x.path), f1(x.e4), f1(x.e4Before)]));
    if (ch.callsUp.length || ch.callsDown.length) sec('Traffic changes (same hours)', ['Method', 'Path', 'Calls today', 'Before (avg)', 'Change'],
      [...ch.callsUp.slice(0, 10), ...ch.callsDown.slice(0, 10)].map((/** @type {any} */ x) => [txt(x.method), code(x.path), f1(x.calls), f1(x.callsBefore), ratio(x.calls, x.callsBefore)]));
    if (ch.appeared.length || ch.vanished.length) sec('Appeared / vanished today', ['Method', 'Path', 'Calls today', 'Before (avg)', ''],
      [...ch.appeared.slice(0, 10).map((/** @type {any} */ x) => [txt(x.method), code(x.path), f1(x.calls), '0', 'new']), ...ch.vanished.slice(0, 10).map((/** @type {any} */ x) => [txt(x.method), code(x.path), '0', f1(x.callsBefore), 'gone'])]);
  }
  if (opt.errors?.endpoints?.length) {
    L.push('## Error texts', '', txt(opt.errors.note || ''), '');
    for (const e of opt.errors.endpoints) {
      L.push(`### ${txt(e.method)} ${code(e.path)} — ${n(Number(e.errors5xx) || 0)} × 5xx`, '', '| Error (digits and IDs masked) | Records | First seen | Example trace |', '|---|---:|---|---|');
      for (const m of e.messages || []) L.push(`| ${txt(m.text)} | ${n(Number(m.count) || 0)} | ${txt(String(m.firstSeen || '').slice(0, 19).replace('T', ' '))} | ${code(m.trace || '')} |`);
      L.push('');
    }
  }
  const sp = opt.spikes || [];
  if (sp.length) sec('Recent spikes', ['Method', 'Path', 'Window', '5xx', 'Share', 'Days before'],
    sp.map((x) => [x.method, code(x.path), `last ${pl(x.window, 'day')}`, n(x.errors5xx), pct(x.errors5xx, x.calls), `${(x.wholeShare * 100).toFixed(2)}%`]),
    'Over the threshold in a recent window and at least 3× the 5xx share of the days before it. Look at what changed.');
  sec('Server errors', ['Method', 'Path', 'Calls', '5xx', 'Share', 'Statuses'],
    r.serverErrors.map((e) => [e.method, code(e.path), n(e.calls), n(e.errors5xx), pct(e.errors5xx, e.calls), st(e.status)]),
    `Rule: 5xx ≥ ${+(th.errorShare * 100).toFixed(3)}% of calls **and** ≥ ${th.errorMin} responses (change with \`--error-share\`, \`--error-min\`).`);
  if (r.errorsBelow.length) sec('Other endpoints with 5xx (below the threshold)', ['Method', 'Path', 'Calls', '5xx', 'Share'],
    r.errorsBelow.slice(0, TOP).map((e) => [e.method, code(e.path), n(e.calls), n(e.errors5xx), pct(e.errors5xx, e.calls)]));
  if (r.clientErrors.length) sec('Client errors (4xx ≥ 10%, without 401/404)', ['Method', 'Path', 'Calls', '4xx', 'Share', 'Statuses'],
    r.clientErrors.map((e) => [e.method, code(e.path), n(e.calls), n(e.errors4xx), pct(e.errors4xx, e.calls), st(e.status)]));
  const why = (/** @type {any} */ s) => (s.kind === 'method_not_in_spec' ? 'path exists, method does not' : 'path not in spec');
  const flag = (/** @type {any} */ s) => (RISKY.test(s.path) && [...s.status.keys()].some((c) => c[0] === '2') ? '⚠ debug/admin path answering 2xx — check auth' : '');
  sec('Undocumented: called, not in the spec', ['Method', 'Path', 'Calls', 'Why', 'Risk', 'Statuses'],
    r.shadow.slice(0, TOP).map((s) => [s.method, code(s.path), n(s.calls), why(s), flag(s), st(s.status, 3)]));
  if (r.ambiguous.length) sec('Possibly separate routes (hint)', ['Method', 'Path seen', 'Counted as', 'Calls'],
    r.ambiguous.map((a) => [a.method, code(a.path), code(a.matched), n(a.calls)]),
    'A word landed on a spec parameter and was counted into that operation. If your app has its own route for it (e.g. `/orders/export`), that route is undocumented; if the parameter is a slug (`/categories/books`), ignore this.');
  if (opt.duplicates) sec('Repeated non-GET requests (duplicates)', ['Method', 'Path', 'Calls', 'Repeats', 'Share', 'Note'],
    opt.duplicates.rows.slice(0, TOP).map((/** @type {any} */ d) => [txt(d.method), code(d.path), n(Number(d.calls) || 0), n(Number(d.repeats) || 0), pct(Number(d.repeats) || 0, Number(d.calls) || 1), txt(d.note || '')]), txt(opt.duplicates.note || ''));
  if (opt.probe) sec('Front-end probe: problems', ['Page', 'Method', 'Path', 'Status', 'ms', 'Per load', 'Problem'],
    opt.probe.rows.filter((/** @type {any} */ x) => x.problem).slice(0, TOP).map((/** @type {any} */ x) => [code(x.page), txt(x.method), code(x.path), String(Number(x.status) || '—'), x.ms == null ? '—' : n(Number(x.ms) || 0), String(Number(x.perLoad) || 0), txt(x.problem)]),
    `${Number(opt.probe.pages) || 0} pages, ${Number(opt.probe.requests) || 0} API requests. ${txt(opt.probe.note || '')}`);
  sec(`Not called in ${winTxt}`, ['Method', 'Path', 'Note'],
    E.filter((e) => e.class === 'not_seen').sort((a, b) => a.path.localeCompare(b.path))
      .map((e) => [e.method, code(e.path), e.periodicHint ? 'looks periodic (report/job/import): check before removing' : '']));
  sec('Deprecated but still called', ['Method', 'Path', 'Calls', 'Last seen', 'Note'],
    E.filter((e) => e.class === 'deprecated_in_use').sort((a, b) => b.calls - a.calls)
      .map((e) => [e.method, code(e.path), n(e.calls), day(e.last_seen), e.calls < th.rare ? 'also rare' : '']));
  sec(`Rare (< ${th.rare} calls)`, ['Method', 'Path', 'Calls', 'Last seen', 'Statuses'],
    E.filter((e) => e.class === 'rare').sort((a, b) => a.calls - b.calls)
      .map((e) => [e.method, code(e.path), n(e.calls), day(e.last_seen), st(e.status)]));
  sec('Used', ['Method', 'Path', 'Calls', '5xx', 'Statuses'],
    E.filter((e) => e.class === 'used').sort((a, b) => b.calls - a.calls)
      .map((e) => [e.method, code(e.path), n(e.calls), n(e.errors5xx), st(e.status)]));

  const kinds = { preflight: 'OPTIONS/HEAD (CORS preflight)', probe: 'scanners and infra paths', not_found_only: 'unknown path, only 404/405 (broken client URLs)' };
  L.push('## Noise (set aside)', '');
  if (!r.noise.length) L.push('_None._');
  for (const [k, label] of Object.entries(kinds)) {
    const items = r.noise.filter((x) => x.kind === k);
    if (!items.length) continue;
    L.push(`- **${label}:** ${pl(items.length, 'pair')}, ${pl(items.reduce((s, x) => s + x.calls, 0), 'request')}. Top: ${items.slice(0, 5).map((x) => `${x.method} ${code(x.path)} (${n(x.calls)})`).join(', ')}`);
  }
  L.push('');
  return L.join('\n');
}

/**
 * Short plain-text summary for the terminal (stderr): the top of each finding, at most `top` rows each.
 * @param {ReturnType<typeof import('./classify.mjs').classify>} r
 * @param {{ top?: number, color?: boolean, spikes?: any[], changes?: any, tz?: string }} [opt]
 */
export function toTerminal(r, opt = {}) {
  const top = opt.top ?? 3;
  const c = opt.color ? { b: '\x1b[1m', r: '\x1b[31m', y: '\x1b[33m', c: '\x1b[36m', d: '\x1b[2m', x: '\x1b[0m' } : { b: '', r: '', y: '', c: '', d: '', x: '' };
  const n = (/** @type {number} */ x) => x.toLocaleString('en-US');
  const clean = (/** @type {string} */ s) => String(s).replace(/[\u0000-\u001f\u007f]/g, ' ');
  const row = (/** @type {string} */ m, /** @type {string} */ p, /** @type {string} */ rest) => `  ${m.padEnd(6)} ${clean(p).padEnd(34)} ${rest}`;
  const t = r.totals;
  const L = [];
  const sec = (/** @type {string} */ color, /** @type {string} */ title, /** @type {string[]} */ rows, /** @type {number} */ total) => {
    if (!total) return;
    L.push(`${color}${c.b}${title}${c.x}`, ...rows.slice(0, top));
    if (total > top) L.push(`${c.d}  … ${total - top} more in report.md${c.x}`);
  };
  const ch = opt.changes;
  if (ch) {
    const pc = (/** @type {number} */ a, /** @type {number} */ b) => (b ? `${a >= b ? '+' : ''}${(((a / b) - 1) * 100).toFixed(0)}%` : 'new');
    L.push(`${c.b}Δ Today vs the same hours before: requests ${pc(ch.totals.calls, ch.totals.callsBefore)}, 5xx ${n(ch.totals.e5)} (before ${n(Math.round(ch.totals.e5Before))})${c.x}`);
    for (const x of ch.errorsUp.slice(0, top)) L.push(row(x.method, x.path, `${n(x.e5)} × 5xx (before ${n(Math.round(x.e5Before))})${x.firstErrorHour == null ? '' : `, from ${hourLabel(ch.today, x.firstErrorHour, opt.tz)}`}`));
    for (const x of ch.callsUp.slice(0, 2)) L.push(row(x.method, x.path, `calls ${pc(x.calls, x.callsBefore)}`));
  }
  const sp = opt.spikes || [];
  sec(c.r, `▲ Recent spikes: ${sp.length}`, sp.map((x) => row(x.method, x.path, `${(x.share * 100).toFixed(1)}% 5xx in the last ${x.window} day${x.window === 1 ? '' : 's'} (before: ${(x.wholeShare * 100).toFixed(1)}%)`)), sp.length);
  sec(c.r, `✖ Server errors: ${t.serverErrors}${t.serverErrorsBelowThreshold ? ` (+${t.serverErrorsBelowThreshold} below threshold)` : ''}`,
    r.serverErrors.map((e) => row(e.method, e.path, `${n(e.errors5xx)} × 5xx  ${((e.errors5xx / e.calls) * 100).toFixed(1)}%`)), t.serverErrors);
  sec(c.y, `! Undocumented (called, not in spec): ${t.shadow}`, r.shadow.map((s) => row(s.method, s.path, `${n(s.calls)} calls`)), t.shadow);
  const ns = r.endpoints.filter((e) => e.class === 'not_seen');
  sec(c.c, `○ Not called in ${r.window.days ?? '?'} days: ${t.not_seen}  ${c.d}(a hint, not a verdict)${c.x}`,
    ns.map((e) => row(e.method, e.path, `0 calls${e.periodicHint ? `  ${c.d}looks periodic${c.x}` : ''}`)), ns.length);
  const dep = r.endpoints.filter((e) => e.class === 'deprecated_in_use');
  sec(c.y, `↓ Deprecated but still called: ${dep.length}`, dep.map((e) => row(e.method, e.path, `${n(e.calls)} calls`)), dep.length);
  return L.join('\n');
}
